using System.Text.Json;
using System.Text.Json.Serialization;

namespace Koras.ApiClient;

/// <summary>
/// An RFC 9457 (formerly RFC 7807) problem details document returned by an API to describe an error.
/// </summary>
public sealed record ProblemDocument
{
    /// <summary>A URI reference that identifies the problem type.</summary>
    [JsonPropertyName("type")]
    public string? Type { get; init; }

    /// <summary>A short, human-readable summary of the problem type.</summary>
    [JsonPropertyName("title")]
    public string? Title { get; init; }

    /// <summary>The HTTP status code generated by the origin server for this occurrence.</summary>
    [JsonPropertyName("status")]
    public int? Status { get; init; }

    /// <summary>A human-readable explanation specific to this occurrence of the problem.</summary>
    [JsonPropertyName("detail")]
    public string? Detail { get; init; }

    /// <summary>A URI reference that identifies the specific occurrence of the problem.</summary>
    [JsonPropertyName("instance")]
    public string? Instance { get; init; }

    /// <summary>
    /// Validation errors keyed by member name, following the ASP.NET Core
    /// <c>ValidationProblemDetails</c> convention.
    /// </summary>
    [JsonPropertyName("errors")]
    public IReadOnlyDictionary<string, string[]>? Errors { get; init; }

    /// <summary>Any additional problem-type-specific members carried by the document.</summary>
    [JsonExtensionData]
    public IDictionary<string, JsonElement>? Extensions { get; init; }
}
